const assert = require('assert');
const { loadPresenceContract } = require('../../features/presence/presenceContract');
const { validateRailwayPhraseDataset } = require('../../features/presence/railwayPresenceDataset');
const { createPresenceUpdateGate } = require('../../features/presence/presenceUpdateGate');
const { HEALTHY_RECOVERY_MS } = require('../../features/presence/presenceUpdateGate');
const { createPresenceMoodCoordinator } = require('../../features/presence/presenceMoodCoordinator');
const { createPresenceMoodCycler } = require('../../features/presence/presenceMoodCycler');
async function main() {
const contract = loadPresenceContract();
const phrases = ['dormant', 'observing', 'pondering', 'displeased'].flatMap(mood => [1, 2].map(index => ({ id: mood + '-' + index, text: mood + ' thought ' + index, mood, symbol: index === 1 ? '👁' : null, rpcDetails: mood + ' thought ' + index, rpcState: 'steady', rpcIconKey: 'skarn_eye' })));
const dataset = { schemaVersion: 1, generatedAt: new Date().toISOString(), phrases };
assert.ok(validateRailwayPhraseDataset(dataset, { expectedCount: 8, minPerMood: 2 }).ok);
assert.ok(!validateRailwayPhraseDataset({ ...dataset, phrases: phrases.slice(1) }, { expectedCount: 8, minPerMood: 2 }).ok);
let now = 0, calls = 0, timeoutFn = null;
const gate = createPresenceUpdateGate({ clock: () => now, setTimeout: fn => { timeoutFn = fn; return 1; }, clearTimeout: () => {} });
assert.strictEqual(gate.canAttempt(), true);
const pending = gate.attempt(() => new Promise(() => {}));
assert.strictEqual(gate.getStatus().inFlight, true);
now = 5000; timeoutFn();
const timeoutResult = await pending;
assert.strictEqual(timeoutResult.reason, 'timeout');
assert.strictEqual(gate.getStatus().suppressionLevel, 1);
now = 35000;
assert.strictEqual(gate.canAttempt(), true);
const rejection = await gate.attempt(() => { throw new Error('offline'); });
assert.strictEqual(rejection.ok, false);
assert.strictEqual(gate.getStatus().suppressionLevel, 2);
now = 155000;
assert.strictEqual((await gate.attempt(() => undefined)).ok, true);
now += HEALTHY_RECOVERY_MS;
assert.strictEqual((await gate.attempt(() => undefined)).suppressionLevel, 1);
now += HEALTHY_RECOVERY_MS;
assert.strictEqual((await gate.attempt(() => undefined)).suppressionLevel, 0);
let state = null;
const coordinator = createPresenceMoodCoordinator({ contract, clock: () => now, random: () => 0.99, readState: () => state, writeState: value => { state = value; } });
const activities = [];
const cycler = createPresenceMoodCycler({ contract, dataset, validationOptions: { expectedCount: 8, minPerMood: 2 }, coordinator, clock: () => now, setActivity: (text, options) => { calls++; activities.push({ text, options }); } });
cycler.cycle(now);
assert.strictEqual(activities[0].options.type, 3);
assert.ok(activities[0].text.includes('thought'));
console.log('Railway presence smoke passed');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
